"""Output writers for partition, bench, runtime plan, and workload summaries."""

import json
import os


def write_partition_py(path, info, onnx_path):
    """Write partition_info.py."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("# Auto-generated partition info\n")
        handle.write(f"# Source: {onnx_path}\n")
        handle.write("# Generated by chiplet_task_estimator.py\n\n")
        handle.write(f"NODE_TO_DEVICE = {json.dumps(info['node_to_device'], indent=2, sort_keys=True)}\n\n")
        handle.write(f"DEVICE_SUBGRAPHS = {json.dumps(info['device_subgraphs'], indent=2, sort_keys=True)}\n\n")
        handle.write(f"SORTED_EXECUTION_ORDER = {json.dumps(info['sorted_execution_order'], indent=2)}\n\n")
        handle.write(f"SUBGRAPH_PLAN = {json.dumps(info['subgraph_plan'], indent=2)}\n")


def write_bench(path, bench_lines):
    """Write a PopNet bench trace."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    ordered = sorted(bench_lines, key=lambda row: (row[0], row[2], row[3]))
    with open(path, "w", encoding="utf-8") as handle:
        for row in ordered:
            handle.write("{} {} {} {} {} {}\n".format(*row))
    return ordered


def write_pim_pe_workload(path, npu_count, node_task_map):
    """Write a per-NPU workload summary."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    summary = [{"cycles": 0, "tasks": 0, "ops": 0, "bytes": 0} for _ in range(max(1, int(npu_count)))]

    for _, tasks in node_task_map.items():
        if not isinstance(tasks, list):
            continue
        for task in tasks:
            if str(task.get("device", "")).upper() != "PIM":
                continue
            pe = int(task.get("pe_id", -1))
            if pe < 0 or pe >= len(summary):
                continue
            summary[pe]["cycles"] += int(max(0, task.get("total_cycles", 0)))
            summary[pe]["tasks"] += 1
            summary[pe]["ops"] += int(max(0, task.get("task_ops", 0)))
            summary[pe]["bytes"] += int(max(0, task.get("task_bytes", 0)))

    with open(path, "w", encoding="utf-8") as handle:
        handle.write("# pe_id cycles tasks ops bytes\n")
        for pe, item in enumerate(summary):
            handle.write(
                f"{pe} {int(item['cycles'])} {int(item['tasks'])} {int(item['ops'])} {int(item['bytes'])}\n"
            )
    return summary


def write_runtime_plan(path, device, events):
    """Write the phase1 runtime event plan."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(f"# device {device}\n")
        handle.write("# format: COMPUTE <cycles> [subgraph_id] [ops=<ops>] [bytes=<bytes>]\n")
        handle.write("#         SEND <peer_x> <peer_y> <bytes> [subgraph_id]\n")
        handle.write("#         RECV <peer_x> <peer_y> <bytes> [subgraph_id]\n")
        for event in events:
            event_type = str(event.get("type", "")).upper()
            subgraph_id = str(event.get("subgraph_id", "NA"))
            if event_type == "COMPUTE":
                cycles = int(max(1, event.get("cycles", 1)))
                ops = int(max(0, event.get("ops", 0)))
                num_bytes = int(max(0, event.get("bytes", 0)))
                if ops > 0 or num_bytes > 0:
                    handle.write(f"COMPUTE {cycles} {subgraph_id} ops={ops} bytes={num_bytes}\n")
                else:
                    handle.write(f"COMPUTE {cycles} {subgraph_id}\n")
            elif event_type in ("SEND", "RECV"):
                peer_x, peer_y = event.get("peer_xy", [0, 0])
                num_bytes = int(max(1, event.get("bytes", 64)))
                handle.write(f"{event_type} {int(peer_x)} {int(peer_y)} {num_bytes} {subgraph_id}\n")
